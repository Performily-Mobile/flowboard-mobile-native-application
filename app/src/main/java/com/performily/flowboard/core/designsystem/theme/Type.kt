import androidx.compose.ui.unit.sp

/**
 * Type scale of the app.
 *
 * Every Material 3 role is defined so no screen falls back to the thin default weights.
 * Headlines and titles are semibold and body text is regular. Body and label roles keep the
 * Material letter spacing (0.1 to 0.4 sp) so small text does not look cramped, the line height
 * is about 1.5 times the size, and secondary text starts at 13 sp so supporting lines stay readable:
 * titleLarge for screen titles, titleMedium for card and section titles, titleSmall for group labels,
 * bodyLarge for the first line of a list row, bodyMedium for its second line, bodySmall for dates
 * and other metadata, labelLarge for buttons and labelMedium for badges and chips.
 */
