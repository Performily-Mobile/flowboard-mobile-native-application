/**
 * Theme of the app: colors, status colors, typography and shapes.
 *
 * Both color schemes define every Material 3 role, so components that read a role the app does not
 * customize (such as tertiary or the surface containers) never fall back to the default purple palette.
 *
 * @param darkTheme whether the dark color scheme is used.
 * @param content content that receives the theme.
 */
@Composable
fun FlowboardTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    CompositionLocalProvider(
        LocalStatusColors provides if (darkTheme) DarkStatusColors else LightStatusColors
    ) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme,
            typography = Typography,
            shapes = FlowboardShapes,
            content = content
        )
    }
}
